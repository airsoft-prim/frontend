import type { ReactNode } from 'react';
import { Anchor, Box, Card, Divider, Group, Text } from '@mantine/core';

interface PalletProps {
  /** Заголовок паллетки; без него содержимое занимает всю высоту */
  title?: string;
  /**
   * Кегль заголовка. Карточки-разделы страницы берут `md`: заголовок читается
   * как заголовок блока, а иконка рядом передаётся крупнее обычной.
   * По умолчанию `sm` — шапка строки списка.
   */
  titleSize?: 'sm' | 'md';
  /**
   * Иконка перед заголовком. Оттенок задаёт сама паллетка, поэтому
   * достаточно передать элемент иконки с нужным размером.
   */
  icon?: ReactNode;
  /**
   * Доля высоты колонки: `1` — одна часть, `2` — две и так далее.
   * Паллетки с `grow` делят высоту колонки пропорционально своим долям
   * (карточка игрока 2/3 и новости 1/3 — это `grow={2}` и `grow={1}`).
   * Без пропа паллетка занимает высоту своего содержимого.
   */
  grow?: number;
  /**
   * Линия между шапкой и содержимым. Берут карточки вкладок: у них заголовок
   * называет вкладку, и линия отделяет его от содержимого, а не строку списка
   * от строки.
   */
  divider?: boolean;
  children: ReactNode;
}

/**
 * Паллетка — базовая карточка страницы: одна тема, своя шапка, внутренние
 * отступы. Все блоки разделов собираются из них, чтобы страницы выглядели
 * однотипно.
 */
export function Pallet({
  title,
  titleSize = 'sm',
  icon,
  grow,
  divider,
  children,
}: PalletProps) {
  return (
    <Card
      withBorder
      padding="md"
      /* Базис нулевой: высота считается от доли, а не от содержимого —
       * тогда соседние паллетки встают ровно в заданных пропорциях */
      style={grow ? { flex: `${grow} 1 0` } : undefined}
    >
      {(title || icon) && (
        <Group gap="xs" wrap="nowrap" align="center" mb="sm">
          {icon && (
            <Box
              aria-hidden="true"
              style={{
                display: 'flex',
                /* Иконки приходят с currentColor, поэтому оттенок шапки
                 * задаётся здесь: он одинаков во всех паллетках */
                color: 'var(--sf-text-secondary)',
              }}
            >
              {icon}
            </Box>
          )}
          {title && (
            <Text fw={600} size={titleSize}>
              {title}
            </Text>
          )}
        </Group>
      )}
      {/* Линия под шапкой: шаг заголовка держит воздух сверху, шаг линии —
       * снизу, чтобы содержимое не прилипало к черте */}
      {divider && <Divider mb="sm" />}
      {/* Содержимое растёт от текста, а не от нуля: с нулевой основой
       * (`flex: 1`) тело схлопывалось в ноль везде, где высоту карточке
       * не задали — в одну колонку на узком экране текст уходил
       * в невидимую прокрутку ноль высоты.
       *
       * Там, где высота есть (колонка раздела, доля `grow`), ничего
       * не меняется: свободное место уходит единственному растущему блоку,
       * а если карточка ниже содержимого — тело ужимается и прокручивает
       * его внутри себя, как и задумано. */}
      <Box style={{ flex: '1 1 auto', minHeight: 0, overflowY: 'auto' }}>
        {children}
      </Box>
    </Card>
  );
}

interface PalletActionProps {
  children: ReactNode;
  icon?: ReactNode;
  /**
   * Адрес раздела, куда ведёт действие. Без него действие остаётся
   * кнопкой-заглушкой: раздел ещё не создан, вести некуда.
   */
  href?: string;
}

/**
 * Действие «Все …» в подвале паллетки.
 *
 * С `href` это обычная ссылка: такой раздел уже есть, и ссылка получает
 * адрес в разметке (клавиатура, средняя кнопка мыши и копирование адреса
 * работают как обычно). Без `href` остаётся кнопкой-заглушкой — для списков,
 * у которых раздела пока нет.
 */
export function PalletAction({ children, icon, href }: PalletActionProps) {
  const style = {
    color: 'var(--sf-text-secondary)',
    display: 'flex',
    gap: 6,
  } as const;

  if (href) {
    return (
      <Anchor
        component="a"
        href={href}
        size="xs"
        underline="hover"
        style={style}
      >
        {children}
        {icon}
      </Anchor>
    );
  }

  return (
    <Anchor
      component="button"
      type="button"
      size="xs"
      underline="hover"
      style={style}
    >
      {children}
      {icon}
    </Anchor>
  );
}
