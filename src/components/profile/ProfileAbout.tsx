import { Box } from '@mantine/core';
import { IconFileText } from '@tabler/icons-react';

import { MarkdownText } from '../MarkdownText';
import { Pallet } from '../Pallet';
import { ABOUT } from './demo';

/**
 * Колонка текста в карточке. Биография — связный текст, а не список полей:
 * строка длиннее 42rem читается плохо, поэтому ширина ограничена, а не
 * растянута на всю карточку (карточка шире текста втрое).
 */
const MEASURE = '42rem';

/**
 * Обёртка карточки с долей высоты.
 *
 * Доля живёт в обёртке, а не в `grow` паллетки: у `grow` основа нулевая, и там,
 * где высоту колонки никто не задаёт (одна колонка на узком экране), карточка
 * схлопывается до заголовка, а содержимое уходит в прокрутку нулевой высоты.
 * Здесь основа по содержимому: на широком экране карточка делит с соседями
 * свободное место, а в одну колонку идёт по своему тексту.
 *
 * Сетка из одной строки растягивает карточку на высоту обёртки: строка `1fr`
 * занимает её целиком, когда высота есть, и равна содержимому, когда её нет.
 */
const GROW_STYLE = {
  display: 'grid',
  gridTemplateRows: '1fr',
  flex: '3 1 auto',
} as const;

/**
 * «Об игроке» — первая вкладка профиля: приветствие, биография и цитата.
 *
 * Текст приходит разметкой (см. ABOUT) и рисуется целиком: выделение
 * приветствия, абзацы и цитату с подписью автора задаёт сам игрок, а не
 * страница — иначе форматирование профиля пришлось бы собирать из полей.
 * Вид блоков — класс `.sf-markdown`: у цитаты полевая черта слева (как
 * у цитаты в макете), подпись автора идёт тише самого текста.
 */
export function ProfileAbout() {
  return (
    <Box style={GROW_STYLE}>
      <Pallet
        title="Об игроке"
        titleSize="md"
        icon={<IconFileText size={22} stroke={1.6} />}
        divider
      >
        <Box style={{ maxWidth: MEASURE }}>
          <MarkdownText markdown={ABOUT} />
        </Box>
      </Pallet>
    </Box>
  );
}
