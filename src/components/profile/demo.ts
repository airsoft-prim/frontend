/** Игра игрока: микрокарточка вкладки «Игры» */
export interface ProfileGame {
  title: string;
  /** Даты проведения: «26 апреля 2025» или «12–13 апреля 2025» */
  dates: string;
  /** Адрес аватара из API; без него карточка показывает инициалы названия */
  avatarUrl?: string;
}

/**
 * Роль в команде и в орг. группе. У команды роли армейские — командир
 * и игрок; у орг. группы свои: во главе лидер, остальные — участники.
 */
export type TeamRole = 'Командир' | 'Игрок';
export type CommitteeRole = 'Лидер' | 'Участник';

/** Команда игрока: микрокарточка вкладки «Команды» */
export interface ProfileTeam {
  name: string;
  role: TeamRole;
  avatarUrl?: string;
}

/** Орг. группа игрока: микрокарточка вкладки «Орг. Группы» */
export interface ProfileCommittee {
  name: string;
  role: CommitteeRole;
  avatarUrl?: string;
}

