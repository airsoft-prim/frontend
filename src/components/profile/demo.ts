/**
 * Контакты профиля. Вид записи решает, как выглядит строка и что делает её
 * действие: у ссылки на внешний ресурс — переход, у адреса и телефона —
 * копирование (переход по адресу и так делает почтовая программа, а вот
 * скопировать телефон удобнее значком).
 */
export interface ProfileContact {
  kind: 'telegram' | 'vk' | 'max' | 'email' | 'phone';
  label: string;
  value: string;
  /** Адрес, если он известен: без него значение остаётся текстом */
  href?: string;
}

