import { useState } from 'react';
import {
  Box,
  Card,
  Group,
  Pagination,
  Select,
  Skeleton,
  Stack,
  Text,
  Title,
  UnstyledButton,
} from '@mantine/core';
import {
  IconArrowsSort,
  IconChevronRight,
  IconMapPin,
  IconUsers,
} from '@tabler/icons-react';

/** Иконки-подсказки в строке: оттенок muted, размер держат сами иконки */
const ROW_ICON_STYLE = {
  color: 'var(--sf-text-muted)',
  flexShrink: 0,
} as const;

/**
 * Название орг. группы — основной текст строки, а не служебный: его полоса темнее
 * остальных заглушек, как основной текст против приглушённой мета-строки.
 */
const TITLE_BAR_STYLE = {
  backgroundColor: 'var(--sf-text-secondary)',
} as const;

/**
 * Эмблема в колоночной карточке: колонка узкая, поэтому круг небольшой
 * и своего размера — тянуться по высоте ему некуда, высоту строки задаёт
 * содержимое.
 */
const EMBLEM_STYLE = {
  flex: '0 0 auto',
  width: 72,
  height: 72,
} as const;

/**
 * Порядок списка: набора в составе у орг. группы нет, поэтому сортировка опирается
 * только на то, что видно в строке — организованные игры, численность, город
 * и название.
 */
const SORT_OPTIONS = [
  { value: 'games', label: 'По организованным играм' },
  { value: 'members', label: 'По числу участников' },
  { value: 'city', label: 'По городу' },
  { value: 'name', label: 'По названию' },
];

/**
 * Сколько орг. групп показываем на странице: число фиксировано, селектора нет.
 * Двенадцать карточек — ровно четыре ряда по три, поэтому последний ряд
 * не остаётся неполным.
 */
const PAGE_SIZE = 12;

/**
 * Число в строке: значение сверху, подпись под ним — как в макете.
 *
 * Подпись не зависит от данных, поэтому стоит настоящим текстом: по ней блок
 * читается и со скелетоном на месте значения. Высота полосы — кегль данных,
 * которые встанут на её место: 26 (`xxl`) — число организованных игр.
 */
function StatBlock({ label }: { label: string }) {
  return (
    <Stack gap={4}>
      <Skeleton height={26} width={56} radius="sm" />
      <Text c="dimmed" size="md">
        {label}
      </Text>
    </Stack>
  );
}

/**
 * Строка списка орг. групп: эмблема, название, подводка, город
 * с численностью, число организованных игр и переход на страницу.
 *
 * Набора в составе у орг. группы нет, поэтому у названия не стоит плашка
 * набора. Середины строки у орг. группы тоже нет: расцветок и снаряжения
 * нет, поэтому свободное место отдано промежутку перед числом.
 *
 * Ось строки задают настоящие элементы: иконки города и численности, подпись
 * числа и переход не зависят от данных, поэтому стоят в разметке сразу — по ним
 * строка читается и со скелетонами. Заглушки остаются только на месте значений
 * из API, и ширина полос задана в пикселях, а не долями колонки: реальные
 * название или город не растягиваются на всю ширину, поэтому и полосы короче.
 *
 * Карточка — строка из двух частей: содержимое и закладка перехода. Переносить
 * её нельзя (`nowrap`), иначе закладка уедет на собственную линию и перестанет
 * тянуться по высоте карточки; содержимое переносит внутренняя строка, у которой
 * для этого стоит `wrap`. Mantine красит подложку карточки в столбец, поэтому
 * направление задано явно.
 */
function CommitteeRowSkeleton() {
  return (
    <Card
      withBorder
      padding="sm"
      /* Карточка — ячейка сетки: высоту задаёт ряд, поэтому строка занимает
       * её целиком и закладка перехода идёт от границы до границы.
       * Поле строки читает и закладка перехода — см. .sf-row-action */
      style={{
        display: 'flex',
        flexDirection: 'row',
        flexWrap: 'nowrap',
        '--sf-row-padding': 'var(--mantine-spacing-sm)',
      }}
    >
      {/* Строку читают слева направо по одной оси, поэтому блоки выровнены
       * по центру — иначе подводка и мета-строка повисли бы у верхнего края.
       * `alignContent` держит по центру и перенесённые линии: в колоночной
       * карточке строка складывается в две */}
      <Group
        wrap="wrap"
        align="center"
        gap="md"
        style={{ flex: 1, minWidth: 0, alignContent: 'center' }}
      >
        <Skeleton radius="50%" visibleFrom="sm" style={EMBLEM_STYLE} />

        {/* minWidth держит самую широкую полосу (подводка, 200px): колонка
         * не сжимает заглушки и не забирает место у числа справа */}
        <Stack gap={8} style={{ minWidth: 200 }}>
          {/* Название стоит одно: набора в составе у орг. группы нет, поэтому
           * плашки у названия тоже нет */}
          <Skeleton
            height={26}
            width={140}
            radius="sm"
            style={TITLE_BAR_STYLE}
          />

          {/* Подводка — одна строка о том, чем занимается орг. группа */}
          <Skeleton height={15} width={200} radius="sm" />

          {/* Город и численность идут парой: где орг. группа и сколько в ней людей */}
          <Group gap={16} wrap="wrap" align="center">
            <Group gap={6} wrap="nowrap" align="center">
              <IconMapPin size={16} stroke={1.6} style={ROW_ICON_STYLE} />
              <Skeleton height={15} width={84} radius="sm" />
            </Group>

            <Group gap={6} wrap="nowrap" align="center">
              <IconUsers size={18} stroke={1.6} style={ROW_ICON_STYLE} />
              <Skeleton height={21} width={36} radius="sm" />
            </Group>
          </Group>
        </Stack>

        {/* Число организованных игр — у правого края строки: свободное место
         * строки забирает промежуток перед ним, а отступ справа отодвигает
         * число от черты закладки перехода */}
        <Box style={{ marginInlineStart: 'auto', marginInlineEnd: 20 }}>
          <StatBlock label="Организовано игр" />
        </Box>
      </Group>

      {/* Переход на страницу — закладка у правого края карточки: нажимается
       * вся полоса во всю высоту, а не шеврон в 24px. Раздела ещё нет —
       * кнопка пока ничего не делает, но нажимается и озвучивается */}
      <UnstyledButton
        className="sf-row-action"
        aria-label="Открыть страницу орг. группы"
      >
        <IconChevronRight size={24} stroke={1.6} />
      </UnstyledButton>
    </Card>
  );
}

/**
 * Лента орг. групп: заголовок с сортировкой, страница карточек и селектор
 * страниц.
 *
 * Список — сетка в три колонки: переключателя вида нет, колоночное отображение
 * здесь единственное — у орг. группы нет ни набора, ни расцветок, поэтому карточке
 * хватает трети ширины. Ряды сетки делят высоту контентной колонки поровну
 * (`gridAutoRows`), поэтому список заполняет её целиком, а карточка растягивается
 * вместе с рядом.
 *
 * Высота: лента занимает контентную колонку целиком, поэтому селектор страниц
 * держится у её нижнего края (`marginTop: auto`), а не поднимается под последнюю
 * карточку, когда список короче колонки.
 */
export function CommitteesFeed() {
  const [sort, setSort] = useState(SORT_OPTIONS[0].value);

  return (
    <Box style={{ display: 'flex', flexDirection: 'column', height: '100%' }}>
      {/* Заголовок и сортировка — одна строка: заголовок открывает раздел,
       * а порядок списка стоит у правого края, где его ищут */}
      <Group
        justify="space-between"
        align="center"
        wrap="wrap"
        gap="sm"
        mb="sm"
      >
        <Title order={3} size="h4">
          Организационные Группы
        </Title>

        <Select
          aria-label="Сортировка: Организационные Группы"
          data={SORT_OPTIONS}
          value={sort}
          onChange={(value) => setSort(value ?? SORT_OPTIONS[0].value)}
          allowDeselect={false}
          leftSection={<IconArrowsSort size={16} stroke={1.6} />}
          /* Ширина под самый длинный вариант — «По организованным играм»:
           * он занимает 188px при паддингах 68, и в поле 240px обрезался */
          w={280}
        />
      </Group>

      <Box
        style={{
          flex: '1 1 auto',
          display: 'grid',
          gridTemplateColumns: 'repeat(3, minmax(0, 1fr))',
          /* Минимум ряда — 0 (`minmax(0, 1fr)`), а не автоматический: с ним
           * ряд считается по содержимому в самой узкой раскладке и вырастает
           * выше своей доли, тогда сетка перерастает колонку и страница
           * прокручивается. С нулём ряд держится ровно в доле колонки */
          gridAutoRows: 'minmax(0, 1fr)',
          gap: 'var(--mantine-spacing-sm)',
        }}
      >
        {Array.from({ length: PAGE_SIZE }, (_, row) => (
          <CommitteeRowSkeleton key={row} />
        ))}
      </Box>

      <Group justify="center" pt="sm" style={{ marginTop: 'auto' }}>
        {/* total — заглушка: реальное число страниц даст API вместе со списком */}
        <Pagination
          defaultValue={1}
          total={4}
          size="sm"
          siblings={1}
          withEdges={false}
        />
      </Group>
    </Box>
  );
}
